CREATE OR REPLACE FUNCTION emg.fn_verifier_stock_tampon_central()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_type_point varchar(20);
BEGIN
    IF NEW.type_stock = 'TAMPON' THEN
        SELECT type INTO v_type_point
        FROM emg.point_vente
        WHERE id = NEW.idpointvente;

        IF v_type_point <> 'CENTRAL' THEN
            RAISE EXCEPTION 'Le stock TAMPON est reserve au point CENTRAL.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION emg.fn_proteger_stock()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF current_setting('emg.stock_write_authorized', true) IS DISTINCT FROM 'on' THEN
        RAISE EXCEPTION 'Le stock ne peut etre modifie que par un mouvement de stock.';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION emg.fn_appliquer_mouvement_stock()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_avant bigint;
    v_apres bigint;
BEGIN
    PERFORM set_config('emg.stock_write_authorized', 'on', true);

    INSERT INTO emg.stock (idpointvente, idproduit, type_stock, quantite)
    VALUES (NEW.idpointvente, NEW.idproduit, NEW.type_stock, 0)
    ON CONFLICT (idpointvente, idproduit, type_stock) DO NOTHING;

    SELECT quantite INTO v_avant
    FROM emg.stock
    WHERE idpointvente = NEW.idpointvente
      AND idproduit = NEW.idproduit
      AND type_stock = NEW.type_stock
    FOR UPDATE;

    v_apres := v_avant + NEW.variation;

    IF v_apres < 0 THEN
        RAISE EXCEPTION
            'Stock insuffisant: point %, produit %, type %, disponible %, variation %.',
            NEW.idpointvente, NEW.idproduit, NEW.type_stock, v_avant, NEW.variation;
    END IF;

    UPDATE emg.stock
       SET quantite = v_apres,
           updated_at = CURRENT_TIMESTAMP
     WHERE idpointvente = NEW.idpointvente
       AND idproduit = NEW.idproduit
       AND type_stock = NEW.type_stock;

    NEW.quantite_avant := v_avant;
    NEW.quantite_apres := v_apres;

    PERFORM set_config('emg.stock_write_authorized', 'off', true);
    RETURN NEW;
END;
$$;


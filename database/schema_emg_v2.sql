CREATE OR REPLACE FUNCTION emg.fn_initialiser_manquant()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_montant numeric(18,2);
    v_statut varchar(20);
BEGIN
    IF NEW.idsituation_revendeur IS NOT NULL THEN
        SELECT montant_manquant, statut INTO v_montant, v_statut
        FROM emg.situation_revendeur
        WHERE id = NEW.idsituation_revendeur;
    ELSE
        SELECT montant_manquant, statut INTO v_montant, v_statut
        FROM emg.situation_point_vente
        WHERE id = NEW.idsituation_point_vente;
    END IF;

    IF v_statut <> 'VALIDEE' OR v_montant <= 0 THEN
        RAISE EXCEPTION 'Un manquant exige une situation validee avec un ecart negatif.';
    END IF;

    NEW.montant_initial := v_montant;
    NEW.solde := v_montant;
    NEW.statut := 'OUVERT';
    NEW.closed_at := NULL;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION emg.fn_proteger_manquant()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF current_setting('emg.manquant_write_authorized', true) IS DISTINCT FROM 'on' THEN
        RAISE EXCEPTION 'Le manquant est mis a jour uniquement par un reglement.';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION emg.fn_appliquer_reglement_manquant()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_solde numeric(18,2);
    v_nouveau_solde numeric(18,2);
BEGIN
    SELECT solde INTO v_solde
    FROM emg.manquant
    WHERE id = NEW.idmanquant
    FOR UPDATE;

    IF v_solde IS NULL THEN
        RAISE EXCEPTION 'Manquant introuvable.';
    END IF;

    IF NEW.montant > v_solde THEN
        RAISE EXCEPTION 'Le reglement % depasse le solde restant %.', NEW.montant, v_solde;
    END IF;

    v_nouveau_solde := v_solde - NEW.montant;
    PERFORM set_config('emg.manquant_write_authorized', 'on', true);

    UPDATE emg.manquant
       SET solde = v_nouveau_solde,
           statut = CASE WHEN v_nouveau_solde = 0 THEN 'REGLE' ELSE 'PARTIEL' END,
           closed_at = CASE WHEN v_nouveau_solde = 0 THEN CURRENT_TIMESTAMP ELSE NULL END
     WHERE id = NEW.idmanquant;

    PERFORM set_config('emg.manquant_write_authorized', 'off', true);
    RETURN NEW;
END;
$$;


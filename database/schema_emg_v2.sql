CREATE OR REPLACE VIEW emg.v_stock_detail AS
SELECT s.id,
       pv.designation AS point_vente,
       pv.type AS type_point,
       c.designation AS compagnie,
       gp.designation AS groupe_produit,
       p.designation AS produit,
       s.type_stock,
       s.quantite,
       s.updated_at
FROM emg.stock s
JOIN emg.point_vente pv ON pv.id = s.idpointvente
JOIN emg.produit p ON p.id = s.idproduit
JOIN emg.groupe_produit gp ON gp.id = p.idgroupe_produit
JOIN emg.compagnie c ON c.id = gp.idcompagnie;

CREATE OR REPLACE VIEW emg.v_commande_compagnie_totaux AS
SELECT cc.id AS idcommande_compagnie,
       cc.reference,
       cc.idcompagnie,
       cc.date_commande,
       cc.type_commande,
       cc.statut,
       coalesce(sum(lcc.montant_brut), 0)::numeric(18,2) AS montant_brut,
       coalesce(sum(lcc.montant_reduction), 0)::numeric(18,2) AS montant_reduction,
       coalesce(sum(lcc.montant_net), 0)::numeric(18,2) AS montant_net
FROM emg.commande_compagnie cc
LEFT JOIN emg.ligne_commande_compagnie lcc
       ON lcc.idcommande_compagnie = cc.id
GROUP BY cc.id, cc.reference, cc.idcompagnie, cc.date_commande,
         cc.type_commande, cc.statut;

CREATE OR REPLACE VIEW emg.v_solde_commande_compagnie AS
SELECT vct.*,
       coalesce(sum(av.montant) FILTER (WHERE vb.id IS NOT NULL), 0)::numeric(18,2)
           AS montant_regle,
       (vct.montant_net
        - coalesce(sum(av.montant) FILTER (WHERE vb.id IS NOT NULL), 0))::numeric(18,2)
           AS solde
FROM emg.v_commande_compagnie_totaux vct
LEFT JOIN emg.affectation_versement av
       ON av.idcommande_compagnie = vct.idcommande_compagnie
LEFT JOIN emg.versement_bancaire vb
       ON vb.id = av.idversement_bancaire
      AND vb.statut = 'VALIDEE'
GROUP BY vct.idcommande_compagnie, vct.reference, vct.idcompagnie,
         vct.date_commande, vct.type_commande, vct.statut,
         vct.montant_brut, vct.montant_reduction, vct.montant_net;

CREATE OR REPLACE VIEW emg.v_objectif_realisation AS
SELECT o.id AS idobjectif,
       o.idgroupe_produit,
       o.date_debut,
       o.date_fin,
       o.montant_cible,
       coalesce(sum(lcc.montant_net) FILTER (WHERE cc.id IS NOT NULL), 0)::numeric(18,2)
           AS montant_realise,
       CASE
           WHEN o.montant_cible = 0 THEN 0
           ELSE round(
               coalesce(sum(lcc.montant_net) FILTER (WHERE cc.id IS NOT NULL), 0)
               * 100 / o.montant_cible,
               2
           )
       END::numeric(10,2) AS taux_realisation
FROM emg.objectif_commercial o
LEFT JOIN emg.produit p
       ON p.idgroupe_produit = o.idgroupe_produit
LEFT JOIN emg.ligne_commande_compagnie lcc
       ON lcc.idproduit = p.id
LEFT JOIN emg.commande_compagnie cc
       ON cc.id = lcc.idcommande_compagnie
      AND cc.statut = 'VALIDEE'
      AND cc.date_commande BETWEEN o.date_debut AND o.date_fin
GROUP BY o.id, o.idgroupe_produit, o.date_debut, o.date_fin, o.montant_cible;

CREATE OR REPLACE VIEW emg.v_manquants_ouverts AS
SELECT m.id,
       CASE
           WHEN m.idsituation_revendeur IS NOT NULL THEN 'REVENDEUR'
           ELSE 'POINT_VENTE'
       END AS niveau,
       m.idsituation_revendeur,
       m.idsituation_point_vente,
       m.montant_initial,
       m.solde,
       m.statut,
       m.created_at
FROM emg.manquant m
WHERE m.statut <> 'REGLE';


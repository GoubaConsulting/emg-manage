CREATE OR REPLACE FUNCTION emg.fn_verifier_role_point_vente()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_type varchar(20);
BEGIN
    IF NEW.role = 'ADMINISTRATEUR' AND NEW.idpointvente IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT type INTO v_type
    FROM emg.point_vente
    WHERE id = NEW.idpointvente AND actif = true;

    IF v_type IS NULL THEN
        RAISE EXCEPTION 'Le point de vente doit exister et etre actif.';
    END IF;

    IF NEW.role = 'DIRECTEUR' AND v_type <> 'CENTRAL' THEN
        RAISE EXCEPTION 'Un directeur doit etre rattache au point CENTRAL.';
    END IF;

    IF NEW.role = 'GERANT' AND v_type <> 'POINT_VENTE' THEN
        RAISE EXCEPTION 'Un gerant doit etre rattache a un point de vente non central.';
    END IF;

    RETURN NEW;
END;
$$;


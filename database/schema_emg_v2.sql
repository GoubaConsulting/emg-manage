CREATE OR REPLACE FUNCTION emg.fn_verifier_livraison_destination()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_type varchar(20);
    v_point_commande bigint;
BEGIN
    SELECT type INTO v_type
    FROM emg.point_vente
    WHERE id = NEW.idpointvente_destination;

    IF v_type <> 'POINT_VENTE' THEN
        RAISE EXCEPTION 'La destination d''une livraison doit etre un point non central.';
    END IF;

    IF NEW.idcommande_point_vente IS NOT NULL THEN
        SELECT idpointvente INTO v_point_commande
        FROM emg.commande_point_vente
        WHERE id = NEW.idcommande_point_vente;

        IF v_point_commande IS DISTINCT FROM NEW.idpointvente_destination THEN
            RAISE EXCEPTION 'La livraison et la commande doivent concerner le meme point.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION emg.fn_commande_point_modifiable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.statut <> 'BROUILLON' THEN
            RAISE EXCEPTION 'Seule une commande interne brouillon peut etre supprimee.';
        END IF;
        RETURN OLD;
    END IF;

    IF OLD.statut IN ('SERVIE', 'REJETEE', 'ANNULEE') THEN
        RAISE EXCEPTION 'La commande interne % est cloturee.', OLD.id;
    END IF;

    IF OLD.statut <> 'BROUILLON' AND (
        NEW.reference IS DISTINCT FROM OLD.reference
        OR NEW.idpointvente IS DISTINCT FROM OLD.idpointvente
        OR NEW.date_commande IS DISTINCT FROM OLD.date_commande
        OR NEW.idcree_par IS DISTINCT FROM OLD.idcree_par
    ) THEN
        RAISE EXCEPTION 'Les donnees principales ne changent plus apres soumission.';
    END IF;

    IF NOT (
        (OLD.statut = 'BROUILLON' AND NEW.statut IN ('BROUILLON', 'SOUMISE', 'ANNULEE'))
        OR
        (OLD.statut = 'SOUMISE' AND NEW.statut IN ('SOUMISE', 'PARTIELLE', 'SERVIE', 'REJETEE'))
        OR
        (OLD.statut = 'PARTIELLE' AND NEW.statut IN ('PARTIELLE', 'SERVIE'))
    ) THEN
        RAISE EXCEPTION 'Transition de statut interne interdite: % vers %.', OLD.statut, NEW.statut;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION emg.fn_ligne_commande_point_modifiable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_parent_id bigint;
    v_statut varchar(20);
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_parent_id := OLD.idcommande_point_vente;
    ELSE
        v_parent_id := NEW.idcommande_point_vente;
    END IF;

    SELECT statut INTO v_statut
    FROM emg.commande_point_vente
    WHERE id = v_parent_id;

    IF v_statut IS NULL AND TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    IF v_statut = 'BROUILLON' THEN
        IF TG_OP = 'DELETE' THEN
            RETURN OLD;
        END IF;
        RETURN NEW;
    END IF;

    IF TG_OP = 'UPDATE'
       AND v_statut IN ('SOUMISE', 'PARTIELLE')
       AND NEW.idcommande_point_vente = OLD.idcommande_point_vente
       AND NEW.idproduit = OLD.idproduit
       AND NEW.quantite_demandee = OLD.quantite_demandee THEN
        RETURN NEW;
    END IF;

    RAISE EXCEPTION 'Apres soumission, seule la quantite acceptee peut etre modifiee.';
END;
$$;


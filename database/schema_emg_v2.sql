CREATE TABLE emg.ligne_commande_compagnie (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idcommande_compagnie bigint NOT NULL,
    idproduit bigint NOT NULL,
    quantite bigint NOT NULL,
    prix_unitaire numeric(18,2) NOT NULL,
    taux_remise_pct numeric(7,4) NOT NULL DEFAULT 0,
    reduction_fixe numeric(18,2) NOT NULL DEFAULT 0,
    montant_brut numeric(18,2) GENERATED ALWAYS AS (
        round(quantite::numeric * prix_unitaire, 2)
    ) STORED,
    montant_reduction numeric(18,2) GENERATED ALWAYS AS (
        round((quantite::numeric * prix_unitaire * taux_remise_pct / 100) + reduction_fixe, 2)
    ) STORED,
    montant_net numeric(18,2) GENERATED ALWAYS AS (
        round((quantite::numeric * prix_unitaire)
              - (quantite::numeric * prix_unitaire * taux_remise_pct / 100)
              - reduction_fixe, 2)
    ) STORED,
    CONSTRAINT fk_ligne_commande_compagnie_commande
        FOREIGN KEY (idcommande_compagnie) REFERENCES emg.commande_compagnie(id)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT fk_ligne_commande_compagnie_produit
        FOREIGN KEY (idproduit) REFERENCES emg.produit(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_ligne_commande_compagnie_produit
        UNIQUE (idcommande_compagnie, idproduit),
    CONSTRAINT ck_ligne_commande_compagnie_quantite CHECK (quantite > 0),
    CONSTRAINT ck_ligne_commande_compagnie_prix CHECK (prix_unitaire >= 0),
    CONSTRAINT ck_ligne_commande_compagnie_taux CHECK (taux_remise_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_ligne_commande_compagnie_reduction CHECK (
        reduction_fixe >= 0 AND montant_net >= 0
    )
);

CREATE INDEX idx_ligne_commande_compagnie_produit
    ON emg.ligne_commande_compagnie (idproduit);

CREATE OR REPLACE FUNCTION emg.fn_verifier_produit_compagnie_commande()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_compagnie_commande bigint;
    v_compagnie_produit bigint;
BEGIN
    SELECT idcompagnie INTO v_compagnie_commande
    FROM emg.commande_compagnie
    WHERE id = NEW.idcommande_compagnie;

    SELECT gp.idcompagnie INTO v_compagnie_produit
    FROM emg.produit p
    JOIN emg.groupe_produit gp ON gp.id = p.idgroupe_produit
    WHERE p.id = NEW.idproduit;

    IF v_compagnie_commande IS DISTINCT FROM v_compagnie_produit THEN
        RAISE EXCEPTION 'Le produit ne correspond pas a la compagnie de la commande.';
    END IF;

    RETURN NEW;
END;
$$;


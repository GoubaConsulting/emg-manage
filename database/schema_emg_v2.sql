CREATE OR REPLACE FUNCTION emg.fn_document_modifiable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.statut <> 'BROUILLON' THEN
        RAISE EXCEPTION 'Le document % est %, il est donc immutable.', OLD.id, OLD.statut;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION emg.fn_ligne_document_modifiable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_parent_id bigint;
    v_statut varchar(20);
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_parent_id := (to_jsonb(OLD) ->> TG_ARGV[1])::bigint;
    ELSE
        v_parent_id := (to_jsonb(NEW) ->> TG_ARGV[1])::bigint;
    END IF;

    EXECUTE format('SELECT statut FROM emg.%I WHERE id = $1', TG_ARGV[0])
       INTO v_statut
       USING v_parent_id;

    -- Lors d'un ON DELETE CASCADE, le parent peut deja ne plus etre visible.
    IF v_statut IS NULL AND TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    IF v_statut IS NULL THEN
        RAISE EXCEPTION 'Document parent % introuvable.', v_parent_id;
    END IF;

    IF v_statut <> 'BROUILLON' THEN
        RAISE EXCEPTION 'Les lignes du document % ne sont plus modifiables.', v_parent_id;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;


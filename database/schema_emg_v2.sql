CREATE OR REPLACE FUNCTION emg.fn_verifier_affectation_versement()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_compagnie_versement bigint;
    v_compagnie_commande bigint;
    v_montant_versement numeric(18,2);
    v_total_commande numeric(18,2);
    v_affecte_versement numeric(18,2);
    v_affecte_commande numeric(18,2);
    v_statut_versement varchar(20);
    v_statut_commande varchar(20);
    v_old_id bigint;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        v_old_id := OLD.id;
    ELSE
        v_old_id := NULL;
    END IF;

    SELECT idcompagnie, montant, statut
      INTO v_compagnie_versement, v_montant_versement, v_statut_versement
    FROM emg.versement_bancaire
    WHERE id = NEW.idversement_bancaire
    FOR UPDATE;

    SELECT idcompagnie, statut
      INTO v_compagnie_commande, v_statut_commande
    FROM emg.commande_compagnie
    WHERE id = NEW.idcommande_compagnie;

    IF v_statut_versement <> 'VALIDEE' OR v_statut_commande <> 'VALIDEE' THEN
        RAISE EXCEPTION 'Le versement et la commande doivent etre valides.';
    END IF;

    IF v_compagnie_versement IS DISTINCT FROM v_compagnie_commande THEN
        RAISE EXCEPTION 'Le versement et la commande concernent des compagnies differentes.';
    END IF;

    SELECT coalesce(sum(montant_net), 0) INTO v_total_commande
    FROM emg.ligne_commande_compagnie
    WHERE idcommande_compagnie = NEW.idcommande_compagnie;

    SELECT coalesce(sum(montant), 0) INTO v_affecte_versement
    FROM emg.affectation_versement
    WHERE idversement_bancaire = NEW.idversement_bancaire
      AND (v_old_id IS NULL OR id <> v_old_id);

    SELECT coalesce(sum(montant), 0) INTO v_affecte_commande
    FROM emg.affectation_versement
    WHERE idcommande_compagnie = NEW.idcommande_compagnie
      AND (v_old_id IS NULL OR id <> v_old_id);

    IF v_affecte_versement + NEW.montant > v_montant_versement THEN
        RAISE EXCEPTION 'Les affectations depassent le montant du versement.';
    END IF;

    IF v_affecte_commande + NEW.montant > v_total_commande THEN
        RAISE EXCEPTION 'Les affectations depassent le montant net de la commande.';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_affectation_versement_verification
BEFORE INSERT OR UPDATE ON emg.affectation_versement
FOR EACH ROW EXECUTE FUNCTION emg.fn_verifier_affectation_versement();

